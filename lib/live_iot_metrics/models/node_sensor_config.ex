defmodule LiveMetrics.Models.NodeSensorConfig do
  @moduledoc """
  Sensor configuration of a node, kept in sync with the node over Web Serial.

  It is not related to `LiveMetrics.Models.Sensor` or the readings: it only mirrors what the
  firmware stores. The integer `id` is generated by the database and is the sensor id sent
  to the node.
  """
  use Ecto.Schema
  import Ecto.Changeset
  import Ecto.Query
  alias LiveMetrics.Repo

  # Must match the drivers supported by the iot-node firmware (SensorConfig.h)
  @drivers ~w(analog dht22_temp dht22_hum ds18b20)

  schema "node_sensor_configs" do
    field :mac, :string
    field :pin, :integer
    field :sensor_type, :string
    field :driver, :string, default: "analog"
    field :precision, :float, default: 1.0
    field :offset, :float, default: 0.0
    field :interval_ms, :integer, default: 10_000

    timestamps(type: :utc_datetime_usec)
  end

  def drivers, do: @drivers

  @doc "`mac` is set programmatically from the connected node, never cast from params."
  def changeset(config, attrs) do
    config
    |> cast(attrs, [:pin, :sensor_type, :driver, :precision, :offset, :interval_ms])
    |> update_change(:sensor_type, &normalize_type/1)
    |> validate_required([:mac, :pin, :sensor_type, :driver, :precision, :offset, :interval_ms])
    |> validate_number(:pin, greater_than_or_equal_to: 0, less_than_or_equal_to: 39)
    |> validate_inclusion(:driver, @drivers)
    # Stored on the node as CSV, and nodes report types in lowercase
    |> validate_format(:sensor_type, ~r/^[a-z0-9_]+$/,
      message: "use lowercase letters, numbers and underscores"
    )
    |> validate_number(:interval_ms, greater_than_or_equal_to: 500)
    |> unique_constraint([:mac, :pin, :driver],
      name: :node_sensor_configs_mac_pin_driver_index,
      error_key: :pin,
      message: "this node already has a sensor with this driver on this pin"
    )
  end

  defp normalize_type(type) when is_binary(type), do: type |> String.trim() |> String.downcase()
  defp normalize_type(type), do: type

  def list_by_mac(mac) do
    __MODULE__
    |> where([c], c.mac == ^mac)
    |> order_by([c], c.id)
    |> Repo.all()
  end

  def get_by_mac!(mac, id), do: Repo.get_by!(__MODULE__, id: id, mac: mac)

  def create(mac, attrs) do
    %__MODULE__{mac: mac}
    |> changeset(attrs)
    |> Repo.insert()
  end

  def update(config, attrs) do
    config
    |> changeset(attrs)
    |> Repo.update()
  end

  def delete(config), do: Repo.delete(config)

  def delete_all_by_mac(mac) do
    {count, _} = __MODULE__ |> where([c], c.mac == ^mac) |> Repo.delete_all()
    count
  end

  @doc "Serial API payload for the firmware `sensor` command."
  def to_serial_command(%__MODULE__{} = config, action) when action in ["add", "update"] do
    %{
      command: "sensor",
      data: %{
        action: action,
        id: config.id,
        pin: config.pin,
        type: config.sensor_type,
        driver: config.driver,
        precision: config.precision,
        offset: config.offset,
        interval: config.interval_ms
      }
    }
  end

  def remove_serial_command(id), do: %{command: "sensor", data: %{action: "remove", id: id}}

  @doc """
  Compares the stored config with the sensor reported by the node (`sensor list` entry).
  Returns `:synced`, `:differs` or `:missing` (not on the node).
  """
  def sync_status(%__MODULE__{}, nil), do: :missing

  def sync_status(%__MODULE__{} = config, node_sensor) when is_map(node_sensor) do
    same? =
      node_sensor["pin"] == config.pin and
        node_sensor["type"] == config.sensor_type and
        node_sensor["driver"] == config.driver and
        node_sensor["interval"] == config.interval_ms and
        close?(node_sensor["precision"], config.precision) and
        close?(node_sensor["offset"], config.offset)

    if same?, do: :synced, else: :differs
  end

  # The node stores floats with 6 decimals and sends them back through ArduinoJson
  defp close?(a, b) when is_number(a) and is_number(b), do: abs(a - b) < 1.0e-4
  defp close?(_a, _b), do: false
end
